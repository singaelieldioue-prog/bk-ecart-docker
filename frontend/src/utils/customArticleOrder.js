const normalizeString = (str) =>
  String(str || "")
    .trim()
    .toUpperCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

const normalizeCodeValue = (value) =>
  normalizeString(value)
    .replace(/-/g, " ")
    .replace(/,/g, ".")
    .replace(/\s+/g, " ")
    .trim();

