export function getCustomArticlePriority(article) {
  if (!article) return Number.MAX_SAFE_INTEGER;

  const codeCandidates = [article.code, article.ref, article.nom];
  for (const code of codeCandidates) {
    const normalized = normalizeCodeValue(code);
    if (normalized && ARTICLE_CODE_ORDER_MAP.has(normalized)) {
      return ARTICLE_CODE_ORDER_MAP.get(normalized);
    }
  }

  const normalizedName = normalizeString(article.nom);
  if (normalizedName) {
    const legacyOrder = CUSTOM_ARTICLES_ORDER.findIndex((name) => normalizeString(name) === normalizedName);
    if (legacyOrder >= 0) return legacyOrder + ARTICLE_CODE_ORDER.length;
  }

  return Number.MAX_SAFE_INTEGER;
}

// Fonction pour trier les articles selon l'ordre personnalisé
export function sortArticlesByCustomOrder(articles) {
  if (!articles || articles.length === 0) return [];

  const articlesWithOrder = articles.map((article) => ({
    article,
    priority: getCustomArticlePriority(article),
  }));

  articlesWithOrder.sort((left, right) => {
    const a = left.priority;
    const b = right.priority;
    if (a !== b) return a - b;

    const catA = (left.article.categorie || "").toUpperCase();
    const catB = (right.article.categorie || "").toUpperCase();
    if (catA !== catB) return catA.localeCompare(catB);

    return (left.article.nom || "").localeCompare(right.article.nom || "");
  });

  return articlesWithOrder.map(({ article }) => article);
}
